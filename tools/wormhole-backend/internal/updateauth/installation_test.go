func writeInstallationFile(t *testing.T, directory, name, content string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(directory, name), []byte(content), 0600); err != nil {
		t.Fatal(err)
	}
}

func TestInstalledTreeProofCoversPayloadAndExpectedTarget(t *testing.T) {
	ctx := context.Background()
	root := filepath.Join(t.TempDir(), "Wormhole")
	resources := filepath.Join(root, "resources")
	if err := os.MkdirAll(resources, 0700); err != nil {
		t.Fatal(err)
	}
	writeInstallationFile(t, root, "Wormhole.exe", "runner")
	writeInstallationFile(t, resources, "app.asar", "original")
	writeInstallationFile(t, resources, "empty", "")
	manifest, err := InventoryInstallation(ctx, root, "v2.4.3", "windows/x64")
	if err != nil || manifest.Entries != 4 {
		t.Fatal(manifest, err)
	}
	key := ed25519.NewKeyFromSeed(bytes.Repeat([]byte{40}, ed25519.SeedSize))
	pub := key.Public().(ed25519.PublicKey)
	if _, err := VerifyInstalledTree(ctx, root, "windows/x64", pub); !errors.Is(err, ErrManifest) {
		t.Fatal("unsigned installation admitted", err)
	}
	signed, err := SignInstallation(manifest, key)
	if err != nil {
		t.Fatal(err)
	}
	proof := root + InstallationProofSuffix
	writeInstallationFile(t, filepath.Dir(proof), filepath.Base(proof), string(signed))
	verified, err := VerifyInstalledTree(ctx, root, "windows/x64", pub)
	if err != nil || verified != manifest {
		t.Fatal("signed installed payload rejected", err)
	}
	if _, err := VerifyInstalledTree(ctx, root, "windows/arm64", pub); !errors.Is(err, ErrManifest) {
		t.Fatal("release for a different architecture admitted", err)
	}
	other := ed25519.NewKeyFromSeed(bytes.Repeat([]byte{41}, ed25519.SeedSize)).Public().(ed25519.PublicKey)
	if _, err := VerifyInstalledTree(ctx, root, "windows/x64", other); !errors.Is(err, ErrSignature) {
		t.Fatal("release signed by a different key admitted", err)
	}
	for _, name := range []string{"unins000.exe", "unins000.dat", "unins004.msg"} {
		writeInstallationFile(t, root, name, "generated by installer")
	}
	if _, err := VerifyInstalledTree(ctx, root, "windows/x64", pub); err != nil {
		t.Fatal("Inno maintenance data invalidated the tree", err)
	}
	for _, extra := range []string{"runtime.dll", "unins00.exe", "unins000.dll", "resources/unins000.exe"} {
		writeInstallationFile(t, root, extra, "unexpected file")
		if _, err := VerifyInstalledTree(ctx, root, "windows/x64", pub); !errors.Is(err, ErrArtifact) {
			t.Fatalf("extra file %q was admitted: %v", extra, err)
		}
		if err := os.Remove(filepath.Join(root, extra)); err != nil {
			t.Fatal(err)
		}
	}
	writeInstallationFile(t, resources, "app.asar", "modified")
	if _, err := VerifyInstalledTree(ctx, root, "windows/x64", pub); !errors.Is(err, ErrArtifact) {
		t.Fatal("same-size payload substitution admitted", err)
	}
	writeInstallationFile(t, resources, "app.asar", "original")
	if err := os.Remove(filepath.Join(resources, "empty")); err != nil {
		t.Fatal(err)
	}
	if _, err := VerifyInstalledTree(ctx, root, "windows/x64", pub); !errors.Is(err, ErrArtifact) {
		t.Fatal("missing file admitted", err)
	}
	writeInstallationFile(t, resources, "empty", "")
	if err := os.Mkdir(filepath.Join(root, "unins001.exe"), 0700); err != nil {
		t.Fatal(err)
	}
	if _, err := VerifyInstalledTree(ctx, root, "windows/x64", pub); !errors.Is(err, ErrArtifact) {
		t.Fatal("unsigned directory with maintenance filename admitted", err)
	}
	canceled, cancel := context.WithCancel(ctx)
	cancel()
	if _, err := VerifyInstalledTree(canceled, root, "windows/x64", pub); !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
	if _, err := InventoryInstallation(canceled, root, "v2.4.3", "windows/x64"); !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
}

func TestInstallationProofFormatIsCanonicalAndDomainSeparated(t *testing.T) {
	ctx := context.Background()
	dir := t.TempDir()
	if _, err := InventoryInstallation(ctx, dir, "v2.4.3", "linux/x64"); !errors.Is(err, ErrArtifact) {
		t.Fatal("empty inventory allowed", err)
	}
	writeInstallationFile(t, dir, "wormhole", "runner")
	m, err := InventoryInstallation(ctx, dir, "v2.4.3", "linux/x64")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := InventoryInstallation(ctx, dir, "2.4.3", "linux/x64"); !errors.Is(err, ErrManifest) {
		t.Fatal("invalid tag allowed", err)
	}
	raw, err := json.Marshal(m)
	if err != nil {
		t.Fatal(err)
	}
	if parsed, err := ParseInstallationInventory(raw); err != nil || parsed != m {
		t.Fatal(parsed, err)
	}
	key := ed25519.NewKeyFromSeed(bytes.Repeat([]byte{31}, ed25519.SeedSize))
	pub := key.Public().(ed25519.PublicKey)
	if _, err := SignInstallation(m, key[:31]); !errors.Is(err, ErrSignature) {
		t.Fatal("invalid key allowed", err)
	}
	bad := m
	bad.TreeSHA256 = strings.Repeat("A", 64)
	if _, err := SignInstallation(bad, key); !errors.Is(err, ErrManifest) {
		t.Fatal("noncanonical digest allowed", err)
	}
	wrongDomain, err := json.Marshal(installationEnvelope{Manifest: m, Signature: ed25519.Sign(key, append([]byte(domain), raw...))})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := verifyInstallationManifest(wrongDomain, pub); !errors.Is(err, ErrSignature) {
		t.Fatal("another protocol's signature admitted", err)
	}
	correct, err := SignInstallation(m, key)
	if err != nil {
		t.Fatal(err)
	}
	for _, bytes := range [][]byte{nil, append([]byte(" "), correct...), bytes.Repeat([]byte{'x'}, MaxInstallationProof+1), bytes.Replace(correct, []byte(`"entries":1`), []byte(`"entries":100001`), 1), bytes.Replace(correct, []byte(`"entries":1`), []byte(`"entries":1,"entries":1`), 1)} {
		if _, err := verifyInstallationManifest(bytes, pub); !errors.Is(err, ErrManifest) {
			t.Fatal("invalid signed encoding allowed", err)
		}
	}
	for _, bytes := range [][]byte{nil, append(raw, '\n'), bytes.Repeat([]byte{'x'}, MaxInstallationProof+1)} {
		if _, err := ParseInstallationInventory(bytes); !errors.Is(err, ErrManifest) {
			t.Fatal("invalid inventory encoding allowed", err)
		}
	}
}

func TestInstallationTargetUsesNativeArchitecture(t *testing.T) {
	for _, c := range []struct{ platform, arch, want string }{
		{"darwin", "arm64", "darwin/universal"}, {"darwin", "amd64", "darwin/universal"},
		{"linux", "arm64", "linux/arm64"}, {"linux", "amd64", "linux/x64"},
		{"windows", "arm64", "windows/arm64"}, {"windows", "amd64", "windows/x64"},
		{"windows", "386", ""}, {"other", "x64", ""},
	} {
		if got := InstallationTarget(c.platform, c.arch); got != c.want {
			t.Fatal(c, got)
		}
	}
}

func TestInstallationDigestRefusesChangedEntriesAndHonorsLimits(t *testing.T) {
	directory := t.TempDir()
	root, err := os.OpenRoot(directory)
	if err != nil {
		t.Fatal(err)
	}
	defer root.Close()
	writeInstallationFile(t, directory, "image", "application")
	writeInstallationFile(t, directory, "other", "application")
	info, err := root.Lstat("image")
	if err != nil {
		t.Fatal(err)
	}
	entry := fs.FileInfoToDirEntry(info)
	ctx := context.Background()
	canceled, cancel := context.WithCancel(ctx)
	cancel()
	for _, tc := range []struct {
		name  string
		ctx   context.Context
		path  string
		limit int64
		want  error
	}{
		{"budget exhausted", ctx, "image", info.Size() - 1, ErrArtifact},
		{"same bytes in a different file", ctx, "other", info.Size(), ErrArtifact},
		{"removed after enumeration", ctx, "missing", info.Size(), ErrArtifact},
		{"cancellation before hashing", canceled, "image", info.Size(), context.Canceled},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if _, _, err := digestInstallationFile(tc.ctx, root, tc.path, entry, tc.limit, make([]byte, 32)); !errors.Is(err, tc.want) {
				t.Fatalf("digest error = %v, want %v", err, tc.want)
			}
		})
	}
	for _, path := range []string{"image", "missing"} {
		if _, err := InventoryInstallation(ctx, filepath.Join(directory, path), "v2.4.3", "windows/x64"); !errors.Is(err, ErrArtifact) {
			t.Fatalf("inventory accepted a non-directory %q: %v", path, err)
		}
	}
}
