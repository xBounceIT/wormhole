CREATE FUNCTION wormhole_data.node_metadata(wormhole_data.nodes) RETURNS jsonb
LANGUAGE sql IMMUTABLE STRICT SET search_path=pg_catalog,pg_temp AS $metadata$
    SELECT pg_catalog.to_jsonb(metadata){{IMPORT_NODE_METADATA}} FROM (
            SELECT ($1).id AS "id",
                ($1).parent_id AS "parentId",
                ($1).owner_user_id AS "ownerUserId",
                ($1).name AS "name",
                ($1).kind AS "kind",
                ($1).sort_order AS "sortOrder",
                ($1).protocol AS "protocol",
                ($1).host AS "host",
                ($1).port AS "port",
                ($1).http_path AS "httpPath",
                ($1).username AS "username",
                ($1).credential_id AS "credentialId",
                ($1).credential_mode AS "credentialMode",
                ($1).credential_slot_id AS "credentialSlotId",
                ($1).use_inline_password AS "useInlinePassword",
                ($1).ssh_auto_sudo AS "sshAutoSudo",
                ($1).http_ignore_cert_errors AS "httpIgnoreCertErrors",
                ($1).tunnel_enabled AS "tunnelEnabled",
                ($1).tunnel_config_id AS "tunnelConfigId",
                ($1).serial_baud_rate AS "serialBaudRate",
                ($1).serial_data_bits AS "serialDataBits",
                ($1).serial_stop_bits AS "serialStopBits",
                ($1).serial_parity AS "serialParity",
                ($1).serial_flow_control AS "serialFlowControl",
                ($1).ssh_key_file_name AS "sshKeyFileName",
                ($1).ssh_known_host_fingerprint AS "sshKnownHostFingerprint",
                ($1).rdp_domain AS "rdpDomain",
                ($1).rdp_screen_size AS "rdpScreenSize",
                ($1).rdp_full_screen AS "rdpFullScreen",
                ($1).rdp_color_depth AS "rdpColorDepth",
                ($1).rdp_use_all_monitors AS "rdpUseAllMonitors",
                ($1).rdp_audio_mode AS "rdpAudioMode",
                ($1).rdp_audio_capture_mode AS "rdpAudioCaptureMode",
                ($1).rdp_keyboard_hook_mode AS "rdpKeyboardHookMode",
                ($1).rdp_redirect_clipboard AS "rdpRedirectClipboard",
                ($1).rdp_redirect_printers AS "rdpRedirectPrinters",
                ($1).rdp_redirect_smart_cards AS "rdpRedirectSmartCards",
                ($1).rdp_redirect_ports AS "rdpRedirectPorts",
                ($1).rdp_redirect_devices AS "rdpRedirectDevices",
                ($1).rdp_redirect_drives AS "rdpRedirectDrives",
                ($1).rdp_connection_speed AS "rdpConnectionSpeed",
                ($1).rdp_desktop_background AS "rdpDesktopBackground",
                ($1).rdp_font_smoothing AS "rdpFontSmoothing",
                ($1).rdp_desktop_composition AS "rdpDesktopComposition",
                ($1).rdp_window_drag AS "rdpWindowDrag",
                ($1).rdp_menu_animation AS "rdpMenuAnimation",
                ($1).rdp_visual_styles AS "rdpVisualStyles",
                ($1).rdp_bitmap_caching AS "rdpBitmapCaching",
                ($1).rdp_auto_reconnect AS "rdpAutoReconnect",
                ($1).rdp_server_authentication AS "rdpServerAuthentication",
                ($1).rdp_gateway_usage_method AS "rdpGatewayUsageMethod",
                ($1).rdp_gateway_hostname AS "rdpGatewayHostname",
                ($1).rdp_gateway_credential_id AS "rdpGatewayCredentialId",
                ($1).rdp_gateway_bypass_local AS "rdpGatewayBypassLocal",
                ($1).rdp_gateway_use_same_creds AS "rdpGatewayUseSameCreds",
                ($1).rdp_use_external_client AS "rdpUseExternalClient"
        ) metadata;
$metadata$;
